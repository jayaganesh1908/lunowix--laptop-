import Image from "next/image";
import { cn } from "@/lib/utils/cn";

/*
 * The Lunowix mark, from the real artwork.
 *
 * TWO FILES, not one theme-aware SVG. The renders are raster, and the light and
 * dark versions are not recolourings of each other — one draws the structural
 * strokes black, the other white, while the orange holds. A single file cannot
 * express that without redrawing it as vector, so both ship and CSS picks.
 *
 * The swap is `hidden dark:block` / `dark:hidden` rather than a JS theme read:
 * the theme is resolved from `localStorage` in an effect, so anything driven by
 * React state would render the wrong logo for a frame on every load. CSS has
 * the class on <html> before paint.
 *
 * Both are marked `priority` — the logo sits in the header on every route, so it
 * is always above the fold, and lazy-loading it just guarantees a visible pop.
 *
 * Generated by `scripts/logo-transparent.py` from the source renders in
 * `public/logos/src/`. Re-run it if the artwork changes; do not hand-edit the
 * PNGs.
 */
export function LunowixMark({
  className,
  /** Use the full stacked lockup (mark over wordmark) instead of the mark alone. */
  lockup = false,
}: {
  className?: string;
  lockup?: boolean;
}) {
  const base = lockup ? "lunowix" : "lunowix-mark";
  // Intrinsic sizes differ slightly between the two renders; `width`/`height`
  // only need to carry the aspect ratio, since the rendered size comes from the
  // class. These are the light variant's, and the dark one is within 1%.
  const [w, h] = lockup ? [962, 689] : [778, 550];

  return (
    <>
      <Image
        src={`/logos/${base}-light.png`}
        alt="Lunowix"
        width={w}
        height={h}
        priority
        className={cn("dark:hidden", className)}
      />
      <Image
        src={`/logos/${base}-dark.png`}
        alt="Lunowix"
        width={w}
        height={h}
        priority
        className={cn("hidden dark:block", className)}
      />
    </>
  );
}
